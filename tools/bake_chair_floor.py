"""Project the drafted chair profiles onto a studio floor from a broad light source."""
import base64
import io
import json
import math
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

folder = Path(__file__).resolve().parents[1] / "radiant/samples/chair"
source = (folder / "drawing-data.js").read_text().split(" = ", 1)[1]
drawing = json.loads(source.strip().rstrip(";"))
pieces = []
for part in drawing["parts"]:
    points = []
    for command, *coords in part["profile"]:
        if command in ("M", "L"):
            points.append(np.array(coords))
        elif command in ("Q", "C"):
            controls = [points[-1], *np.array(coords).reshape(-1, 2)]
            degree = len(controls) - 1
            for t in np.linspace(0, 1, 13)[1:]:
                points.append(sum(p * math.comb(degree, j) * t**j * (1-t)**(degree-j)
                                  for j, p in enumerate(controls)))
    starts = [part["x"]]
    if part["paired"]:
        starts.append(drawing["width"] - part["x"] - part["width"])
    for x in starts:
        pieces.append((x, part["width"], np.array(points)))

side = 320
floor = np.zeros((side, side))
samples = 96
for i in range(samples):
    r = math.sqrt((i + .5) / samples)
    angle = i * 2.39996323
    dx, dz = .29 + .88*r*math.cos(angle), -.27 + .88*r*math.sin(angle)
    mask = Image.new("L", (side, side))
    draw = ImageDraw.Draw(mask)
    for x, width, profile in pieces:
        y = drawing["height"] - profile[:, 1]
        u = x - drawing["width"]/2 + y*dx
        v = profile[:, 0] - drawing["depth"]/2 + y*dz
        left = list(map(tuple, np.round((np.stack((u,v),axis=1)/2200+.5)*side).astype(int)))
        right = [(round(a+width*side/2200), b) for a,b in left]
        draw.polygon(left, fill=255)
        draw.polygon(right, fill=255)
        for j in range(len(left)):
            draw.polygon([left[j-1],left[j],right[j],right[j-1]],fill=255)
    floor += np.asarray(mask, dtype=float)/255
edges = np.minimum(np.arange(side), np.arange(side)[::-1])
fade = np.minimum.outer(edges,edges).clip(0,20)/20
result = Image.fromarray(np.uint8(255*(1 - .36*floor/samples*fade))).filter(ImageFilter.GaussianBlur(.8))
raw = io.BytesIO()
result.save(raw,format="PNG")
url = "data:image/png;base64," + base64.b64encode(raw.getvalue()).decode()
(folder/"floor-shadow.js").write_text("// Generated by tools/bake_chair_floor.py\nconst CHAIR_FLOOR = " + json.dumps(url) + ";\n")

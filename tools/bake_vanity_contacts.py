"""Bake ambient visibility for the V01 board faces and display floor, in millimetres."""
import base64
import io
import json
from pathlib import Path

import numpy as np
from PIL import Image

folder = Path(__file__).resolve().parents[1] / 'radiant/samples/vanity'
text = (folder / 'drawing-data.js').read_text()
parts = json.loads(text[text.index('{'):text.rindex('}')+1])['parts']
names = ['left', 'right', 'back', 'base', 'shelf', 'plinth', 'upper', 'lower']
bounds = {}
for name, (x, y, z, w, h, d) in parts.items():
    bounds[name] = (np.array([x,850-y-h,z]), np.array([x+w,850-y,z+d]))

def visibility(points, normal_axis, sign, skip):
    """Cosine-weighted deterministic hemisphere rays against the other board envelopes."""
    axes = [a for a in range(3) if a != normal_axis]
    points = points.copy()
    points[:,normal_axis] += sign * .25
    total = np.zeros(len(points))
    count = 96
    for i in range(count):
        r = np.sqrt((i+.5)/count)
        angle = i * 2.39996323
        direction = np.zeros(3)
        direction[normal_axis] = sign*np.sqrt(1-r*r)
        direction[axes] = [r*np.cos(angle), r*np.sin(angle)]
        inv = 1 / np.where(np.abs(direction)<1e-8, 1e-8, direction)
        near = np.full(len(points),np.inf)
        for name, (lo, hi) in bounds.items():
            if name == skip: continue
            a,b = (lo-points)*inv,(hi-points)*inv
            enter = np.minimum(a,b).max(axis=1)
            leave = np.maximum(a,b).min(axis=1)
            hit = leave >= np.maximum(0,enter)
            near[hit] = np.minimum(near[hit],np.maximum(0,enter[hit]))
        total += np.exp(-near/360)
    return np.uint8(255*(1-total/count))

def image_data(image):
    data = io.BytesIO()
    image.save(data,format='PNG')
    return 'data:image/png;base64,'+base64.b64encode(data.getvalue()).decode()

# One row per board, columns +X, -X, +Y, -Y, +Z, -Z. One-pixel gutters isolate neighbours.
size=36
atlas=Image.new('L',(6*(size+2),len(names)*(size+2)),255)
for row,name in enumerate(names):
    lo,hi=bounds[name]
    for face in range(6):
        axis=face//2
        sign=1 if face%2==0 else -1
        axes=[a for a in range(3) if a != axis]
        uv=np.indices((size,size))[::-1].reshape(2,-1).T/(size-1)
        p=np.tile(lo,(len(uv),1)).astype(float)
        p[:,axes]=lo[axes]+uv*(hi-lo)[axes]
        p[:,axis]=(hi if sign==1 else lo)[axis]
        grey=visibility(p,axis,sign,name).reshape(size,size)
        atlas.paste(Image.fromarray(np.pad(grey,1,mode='edge')), (face*(size+2),row*(size+2)))
side=128
uv=np.indices((side,side))[::-1].reshape(2,-1).T/(side-1)
points=np.zeros((len(uv),3))
points[:,[0,2]]=(uv-.5)*2200+[345,250]
ambient = visibility(points,1,1,None)/255
# Estimate the visible area of a broad studio key at each point on the floor.
key = np.zeros(len(points))
for i in range(96):
    angle = i*2.39996323
    r = np.sqrt((i+.5)/96)
    light = [-850+900*r*np.cos(angle), 1600, 1150+1000*r*np.sin(angle)]
    inv = 1/np.where(np.abs(light-points)<1e-8,1e-8,light-points)
    blocked = np.zeros(len(points),dtype=bool)
    for lo,hi in bounds.values():
        a,b = (lo-points)*inv,(hi-points)*inv
        enter = np.minimum(a,b).max(axis=1)
        leave = np.maximum(a,b).min(axis=1)
        blocked |= (leave>np.maximum(enter,0)) & (enter<1)
    key += ~blocked
# Fade the finite ground receiver into the surrounding studio sweep.
edge=np.minimum(uv,1-uv).min(axis=1)
fade=np.clip(edge/.16,0,1)
fade=fade*fade*(3-2*fade)
floor=Image.fromarray(np.uint8(255*(1-(1-.65*ambient-.35*key/96)*fade)).reshape(side,side))
data=dict(boards=names,tile=size,atlas=image_data(atlas),floor=image_data(floor))
(folder/'contacts.js').write_text('// Generated by tools/bake_vanity_contacts.py\nconst VANITY_CONTACTS = '+json.dumps(data)+';\n')

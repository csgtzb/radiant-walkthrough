"""Compile the dimensioned front and side elevations into offline viewer data."""
import json
import re
from pathlib import Path
from xml.etree import ElementTree as ET

folder = Path(__file__).resolve().parents[1] / "radiant/samples/chair"
drawing = ET.parse(folder / "drawing.svg")
front = drawing.find(".//*[@id='front']")
side = drawing.find(".//*[@id='side']")
spans = {rect.get("data-span"): [float(rect.get("x")), float(rect.get("width"))]
         for rect in front.findall(".//*[@data-span]")}
parts = []
for profile in side.findall(".//*[@data-span]"):
    commands = []
    for match in re.finditer(r"([MLQCZ])([^MLQCZ]*)", profile.attrib["d"]):
        command, coords = match.groups()
        values = list(map(float, coords.split()))
        assert len(values) == {"M": 2, "L": 2, "Q": 4, "C": 6, "Z": 0}[command]
        commands.append([command, *values])
    x, width = spans[profile.attrib["data-span"]]
    parts.append(dict(name=profile.attrib["id"], x=x, width=width, paired="data-pair" in profile.attrib,
                      finish=profile.get("data-finish", "wood"), grain=profile.get("data-grain"),
                      profile=commands))
data = dict(width=float(front.attrib["data-width"]), height=float(side.attrib["data-height"]),
            depth=float(side.attrib["data-depth"]), parts=parts)
(folder / "drawing-data.js").write_text("// Generated by tools/read_chair_drawing.py\nconst CHAIR_DRAWING = " +
                                       json.dumps(data, separators=(",", ":")) + ";\n")

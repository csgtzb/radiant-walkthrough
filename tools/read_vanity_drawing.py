"""Read the V01 cabinet's paired, millimetre-based SVG projections (standard library)."""
import json
import math
import re
import xml.etree.ElementTree as ET
from pathlib import Path

folder = Path(__file__).resolve().parents[1] / 'radiant/samples/vanity'
drawing = ET.parse(folder / 'drawing.svg')
ns = {'s': 'http://www.w3.org/2000/svg'}


def rectangles(view):
    result = {}
    for rect in drawing.findall(f".//s:g[@id='{view}']//s:rect[@data-part]", ns):
        for key in rect.attrib['data-part'].split():
            if key in result:
                raise ValueError(f'Duplicate {view} part {key}')
            result[key] = [float(rect.get(k, 0)) for k in ('x', 'y', 'width', 'height')]
    return result


front, side = rectangles('front'), rectangles('side')
if front.keys() != side.keys():
    raise ValueError('Front and section part names must match')
parts = {}
for name, (x, down, width, height) in front.items():
    z, side_down, depth, side_height = side[name]
    if (down, height) != (side_down, side_height) or min(width, height, depth) <= 0:
        raise ValueError(f'Inconsistent dimensions for {name}')
    parts[name] = [x, down, z, width, height, depth]

plan = drawing.find(".//*[@id='top-plan']")
if [float(plan.get(k)) for k in ('width', 'height')] != [parts['top'][3], parts['top'][5]]:
    raise ValueError('Countertop plan and elevations disagree')
ellipse = drawing.find(".//*[@id='bowl-plan']")
cx, cz, rx, rz = (float(ellipse.get(k)) for k in ('cx', 'cy', 'rx', 'ry'))
section = drawing.find(".//*[@id='bowl-section']").get('d')
# The section contains two symmetric quadratic arcs. Revolve the front half about the drain.
pattern = r'M([\d.]+) ([\d.]+) Q([\d.]+) ([\d.]+) ([\d.]+) ([\d.]+) Q([\d.]+) ([\d.]+) ([\d.]+) ([\d.]+)'
match = re.fullmatch(pattern, section)
if not match:
    raise ValueError('Expected a symmetric M Q Q basin section')
left, top, lc, ly, mid, bottom, rc, ry_ctrl, right, end_y = map(float, match.groups())
if (left, right, mid, top, end_y, ly) != (cz-rz, cz+rz, cz, parts['top'][4], parts['top'][4], ry_ctrl) or not math.isclose(mid-lc, rc-mid):
    raise ValueError('Basin section and plan disagree')
reed = drawing.find(".//*[@id='reed']")
data = dict(parts=parts, basin=dict(cx=cx, cz=cz, rx=rx, rz=rz, rimDepth=top, bottom=bottom,
            controlRadius=rc-mid, controlDepth=ry_ctrl), reedPitch=float(reed.get('width')))
(folder / 'drawing-data.js').write_text('// Generated by tools/read_vanity_drawing.py from drawing.svg (mm).\nconst VANITY_DRAWING = '
    + json.dumps(data, indent=2) + ';\n', encoding='utf-8')
